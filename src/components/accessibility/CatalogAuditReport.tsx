import React, { useState } from 'react';
import { CATALOG_AUDIT_DATA, calculateAuditScorecard } from '../../design-system/accessibility/a11yAuditor';
import { AuditIssue } from '../../design-system/accessibility/types';
import { useAccessibility } from '../../design-system/accessibility/AccessibilityContext';
import {
  ShieldAlert,
  CheckCircle2,
  AlertTriangle,
  Info,
  Search,
  Filter,
  Download,
  Sparkles,
  Layers,
  Wand2,
  Check,
} from 'lucide-react';

export function CatalogAuditReport() {
  const { applyPreset, announce } = useAccessibility();
  const [selectedCategory, setSelectedCategory] = useState<string>('all');
  const [selectedSeverity, setSelectedSeverity] = useState<string>('all');
  const [searchQuery, setSearchQuery] = useState<string>('');
  const [issuesList, setIssuesList] = useState<AuditIssue[]>(CATALOG_AUDIT_DATA);
  const [appliedFixes, setAppliedFixes] = useState<string[]>([]);

  const scorecard = calculateAuditScorecard(issuesList);

  const filteredIssues = issuesList.filter((issue) => {
    const matchesCategory = selectedCategory === 'all' || issue.category === selectedCategory;
    const matchesSeverity = selectedSeverity === 'all' || issue.severity === selectedSeverity;
    const matchesSearch =
      searchQuery === '' ||
      issue.title.toLowerCase().includes(searchQuery.toLowerCase()) ||
      issue.description.toLowerCase().includes(searchQuery.toLowerCase()) ||
      issue.affectedComponent.toLowerCase().includes(searchQuery.toLowerCase()) ||
      issue.wcagCriterion.toLowerCase().includes(searchQuery.toLowerCase());

    return matchesCategory && matchesSeverity && matchesSearch;
  });

  const handleApplyFix = (issueId: string) => {
    setIssuesList((prev) =>
      prev.map((item) => {
        if (item.id === issueId) {
          return { ...item, severity: 'compliant', remediation: 'Remediation patch active: WCAG standard applied.' };
        }
        return item;
      })
    );
    setAppliedFixes((prev) => [...prev, issueId]);
    announce(`Applied accessibility remediation patch for ${issueId}`, 'polite');
  };

  const handleApplyAllFixes = () => {
    applyPreset('wcag-aaa');
    setIssuesList((prev) =>
      prev.map((item) => ({
        ...item,
        severity: 'compliant',
        remediation: 'Remediation patch active: Full WCAG AAA standard applied.',
      }))
    );
    setAppliedFixes(issuesList.map((i) => i.id));
    announce('Applied full WCAG 2.2 AAA global accessibility remediation across all catalog items', 'assertive');
  };

  const handleExportVPAT = () => {
    const vpatDoc = `# Master UI/UX Style Library — VPAT & WCAG 2.2 Accessibility Conformance Report
Date: ${new Date().toLocaleDateString()}
Standard: Web Content Accessibility Guidelines (WCAG) 2.2 (Level A, AA, and AAA)

## Overall Scorecard Summary
- **Overall Accessibility Health Score**: ${scorecard.score}/100
- **Conformance Status**: ${scorecard.wcagLevelEstimate}
- **Total Audited Criteria**: ${scorecard.total}
- **Fully Compliant**: ${scorecard.compliant}
- **Moderate / Minor Notices**: ${scorecard.moderate}
- **Serious / Action Required**: ${scorecard.serious}
- **Critical Blockers**: ${scorecard.critical}

## Detailed Evaluation Table
| Criterion | Domain | Component | Severity | Title | Status |
|---|---|---|---|---|---|
${issuesList
  .map(
    (i) =>
      `| ${i.wcagCriterion} | ${i.category.toUpperCase()} | ${i.affectedComponent} | ${i.severity.toUpperCase()} | ${i.title} | ${i.severity === 'compliant' ? 'Supported' : 'Partially Supported'} |`
  )
  .join('\n')}

---
Generated by Master UI/UX Accessibility Validation Engine.`;

    const blob = new Blob([vpatDoc], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `accessibility_vpat_report_${Date.now()}.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="p-6 md:p-8 rounded-3xl bg-zinc-950/80 border border-zinc-800 space-y-6">
      {/* Header & Scorecard Bar */}
      <div className="flex flex-col lg:flex-row lg:items-center justify-between gap-6 pb-6 border-b border-zinc-800">
        <div className="space-y-2">
          <div className="flex items-center gap-2.5">
            <div className="p-2.5 rounded-2xl bg-cyan-500/20 text-cyan-400 border border-cyan-500/30">
              <ShieldAlert className="w-5 h-5" />
            </div>
            <h3 className="text-xl font-bold text-white font-mono flex items-center gap-3">
              Automated Catalog Accessibility Audit
              <span className="text-xs px-2.5 py-0.5 rounded-full bg-emerald-500/20 text-emerald-300 border border-emerald-500/30 font-mono">
                {scorecard.wcagLevelEstimate}
              </span>
            </h3>
          </div>
          <p className="text-xs text-zinc-400 max-w-2xl leading-relaxed">
            Continuous diagnostic evaluation of contrast ratios, visible focus indicators, touch bounding boxes, keyboard traps, state attributes, motion safety, and sensory redundancy.
          </p>
        </div>

        {/* Global Action Group */}
        <div className="flex flex-wrap items-center gap-3">
          <button
            onClick={handleApplyAllFixes}
            className="px-4 py-2.5 rounded-xl bg-cyan-500 hover:bg-cyan-400 text-black text-xs font-mono font-bold flex items-center gap-2 shadow-lg shadow-cyan-500/20 transition-all active:scale-95"
          >
            <Sparkles className="w-4 h-4" /> 1-Click Harmonize All (AAA)
          </button>

          <button
            onClick={handleExportVPAT}
            className="px-4 py-2.5 rounded-xl bg-white/5 hover:bg-white/10 border border-white/10 text-xs font-mono font-bold text-white flex items-center gap-2 transition-all"
          >
            <Download className="w-4 h-4 text-cyan-400" /> Export VPAT Report
          </button>
        </div>
      </div>

      {/* Scorecard Metrics Row */}
      <div className="grid grid-cols-2 md:grid-cols-4 gap-4">
        <div className="p-4 rounded-2xl bg-black/40 border border-zinc-800 space-y-1">
          <div className="text-[11px] font-mono text-zinc-400 uppercase">Health Score</div>
          <div className="text-2xl font-mono font-black text-emerald-400">{scorecard.score} / 100</div>
          <div className="text-[10px] text-zinc-500">WCAG 2.2 Algorithm</div>
        </div>

        <div className="p-4 rounded-2xl bg-black/40 border border-zinc-800 space-y-1">
          <div className="text-[11px] font-mono text-zinc-400 uppercase">Compliant Criteria</div>
          <div className="text-2xl font-mono font-black text-cyan-400">
            {scorecard.compliant} <span className="text-sm font-normal text-zinc-500">/ {scorecard.total}</span>
          </div>
          <div className="text-[10px] text-zinc-500">Passing Level AA/AAA</div>
        </div>

        <div className="p-4 rounded-2xl bg-black/40 border border-zinc-800 space-y-1">
          <div className="text-[11px] font-mono text-zinc-400 uppercase">Notices / Moderate</div>
          <div className="text-2xl font-mono font-black text-amber-400">{scorecard.moderate}</div>
          <div className="text-[10px] text-zinc-500">Minor Optimizations</div>
        </div>

        <div className="p-4 rounded-2xl bg-black/40 border border-zinc-800 space-y-1">
          <div className="text-[11px] font-mono text-zinc-400 uppercase">Serious Issues</div>
          <div className="text-2xl font-mono font-black text-rose-400">{scorecard.serious}</div>
          <div className="text-[10px] text-zinc-500">Requires Override</div>
        </div>
      </div>

      {/* Filter & Search Toolbar */}
      <div className="flex flex-col md:flex-row items-center justify-between gap-4 p-3 rounded-2xl bg-zinc-900/60 border border-zinc-800">
        <div className="flex items-center gap-2 w-full md:w-auto overflow-x-auto pb-1 md:pb-0">
          {[
            { id: 'all', label: 'All Domains' },
            { id: 'contrast', label: '1. Contrast' },
            { id: 'focus', label: '2. Focus' },
            { id: 'keyboard', label: '3. Keyboard' },
            { id: 'touch-targets', label: '4. Touch Targets' },
            { id: 'state-communication', label: '5. State ARIA' },
            { id: 'motion', label: '6. Motion' },
            { id: 'sound-dependence', label: '7. Sound' },
          ].map((cat) => (
            <button
              key={cat.id}
              onClick={() => setSelectedCategory(cat.id)}
              className={`px-3 py-1.5 rounded-xl text-xs font-mono font-bold whitespace-nowrap transition-all ${
                selectedCategory === cat.id
                  ? 'bg-cyan-500 text-black shadow-md'
                  : 'bg-black/30 text-zinc-400 hover:text-white'
              }`}
            >
              {cat.label}
            </button>
          ))}
        </div>

        <div className="flex items-center gap-2 w-full md:w-auto">
          <div className="relative flex-1 md:w-56">
            <Search className="w-3.5 h-3.5 absolute left-3 top-1/2 -translate-y-1/2 text-zinc-500" />
            <input
              type="text"
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              placeholder="Search audit rules..."
              className="w-full pl-8 pr-3 py-1.5 rounded-xl bg-black/40 border border-zinc-700 text-xs font-mono text-white focus:outline-none focus:border-cyan-400"
            />
          </div>
        </div>
      </div>

      {/* Issue Cards Feed */}
      <div className="space-y-3">
        {filteredIssues.length === 0 ? (
          <div className="p-8 text-center text-zinc-500 font-mono text-xs">
            No issues match the selected filters.
          </div>
        ) : (
          filteredIssues.map((issue) => {
            const isCompliant = issue.severity === 'compliant';
            const isSerious = issue.severity === 'serious';
            const isModerate = issue.severity === 'moderate';

            return (
              <div
                key={issue.id}
                className={`p-5 rounded-2xl border transition-all space-y-3 ${
                  isCompliant
                    ? 'bg-emerald-950/10 border-emerald-500/20'
                    : isSerious
                      ? 'bg-red-950/10 border-red-500/30'
                      : 'bg-amber-950/10 border-amber-500/30'
                }`}
              >
                <div className="flex flex-col md:flex-row md:items-center justify-between gap-3">
                  <div className="flex items-center gap-2.5">
                    {isCompliant ? (
                      <CheckCircle2 className="w-4 h-4 text-emerald-400 shrink-0" />
                    ) : isSerious ? (
                      <AlertTriangle className="w-4 h-4 text-red-400 shrink-0" />
                    ) : (
                      <Info className="w-4 h-4 text-amber-400 shrink-0" />
                    )}
                    <div>
                      <span className="font-bold text-sm text-white font-mono">{issue.title}</span>
                      <span className="ml-2 text-[10px] font-mono text-zinc-400 uppercase">
                        [{issue.wcagCriterion}]
                      </span>
                    </div>
                  </div>

                  <div className="flex items-center gap-2">
                    <span
                      className={`text-[10px] px-2.5 py-0.5 rounded-full font-mono font-bold uppercase ${
                        isCompliant
                          ? 'bg-emerald-500/20 text-emerald-400 border border-emerald-500/30'
                          : isSerious
                            ? 'bg-red-500/20 text-red-400 border border-red-500/30'
                            : 'bg-amber-500/20 text-amber-400 border border-amber-500/30'
                      }`}
                    >
                      {issue.severity}
                    </span>

                    {issue.autoFixAvailable && !isCompliant && (
                      <button
                        onClick={() => handleApplyFix(issue.id)}
                        className="px-3 py-1 rounded-xl bg-white/10 hover:bg-white/20 text-xs font-mono font-bold text-white flex items-center gap-1 transition-all"
                      >
                        <Wand2 className="w-3 h-3 text-cyan-400" /> Apply Patch
                      </button>
                    )}
                  </div>
                </div>

                <p className="text-xs text-zinc-300 leading-relaxed font-sans">{issue.description}</p>

                <div className="p-3 rounded-xl bg-black/40 border border-white/5 flex flex-col md:flex-row md:items-center justify-between gap-2 text-[11px] font-mono">
                  <div className="text-zinc-400">
                    <strong className="text-zinc-300">Affected:</strong> {issue.affectedComponent}
                  </div>
                  <div className="text-cyan-300">
                    <strong className="text-zinc-300">Standard Action:</strong> {issue.remediation}
                  </div>
                </div>
              </div>
            );
          })
        )}
      </div>
    </div>
  );
}
